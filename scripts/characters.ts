// prints src/characters.ts: every character that hanzi-writer-data has strokes for.
// run `bun run characters` when hanzi-writer moves to a new data version.
const DATA_VERSION = '2.0.1';

const url = `https://data.jsdelivr.com/v1/packages/npm/hanzi-writer-data@${DATA_VERSION}?structure=flat`;
const { files } = (await (await fetch(url)).json()) as { files: { name: string }[] };
const chars = files
  .map((file) => file.name.match(/^\/(.)\.json$/u)?.[1])
  .filter((char) => char !== undefined)
  .sort()
  .join('');

console.log(`// generated by scripts/characters.ts from hanzi-writer-data ${DATA_VERSION}, do not edit
export const SUPPORTED = new Set('${chars}');`);
